export function personalReading(chart) {
  const moon = chart.grahas.find((g) => g.graha === 'moon');
  const lagnaLord = chart.grahas.find(
    (g) => g.graha === signLords[chart.lagna.rashi],
  );
  const moonLord = chart.grahas.find((g) => g.graha === signLords[moon.rashi]);
  const seventh = chart.bhavas.find((h) => h.bhava === 7);
  const seventhLord = chart.grahas.find(
    (g) => g.graha === signLords[seventh.rashi],
  );
  const venus = chart.grahas.find((g) => g.graha === 'venus');
  const themes = [
    { planet: lagnaLord, from: 'lagna', theme: planetThemes[lagnaLord.graha] },
  ];
  if (moonLord.graha !== lagnaLord.graha)
    themes.push({
      planet: moonLord,
      from: 'moon',
      theme: planetThemes[moonLord.graha],
    });
  return {
    themes,
    seventh,
    seventhLord,
    venus,
    relationshipTheme: planetThemes[seventhLord.graha].relationship,
  };
}
